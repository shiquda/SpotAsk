"""Markdown report generation from raw measurements."""

from __future__ import annotations

import json
from pathlib import Path

from .common import stats

TEXT_PREVIEW = 6


def _fmt(value, suffix: str = "") -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.2f}{suffix}"
    return f"{value}{suffix}"


def _range(values) -> str:
    data = stats(values)
    if data["median"] is None:
        return "n/a"
    return f"{data['median']:.2f} ({data['min']:.2f}–{data['max']:.2f})"


def _table(headers, rows) -> str:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        lines.append("| " + " | ".join(str(cell).replace("|", "\\|").replace("\n", " ") for cell in row) + " |")
    return "\n".join(lines)


def _compact(value) -> str:
    """Keeps evidence readable and bounded inside the report."""
    if isinstance(value, dict):
        trimmed = {}
        for key, item in value.items():
            if key in ("checks", "failed_checks", "texts", "formulas") and isinstance(item, list):
                items = item[:TEXT_PREVIEW]
                trimmed[key] = items
                if len(item) > TEXT_PREVIEW:
                    trimmed[f"{key}_total"] = len(item)
            else:
                trimmed[key] = item
        return json.dumps(trimmed, ensure_ascii=False, indent=2, sort_keys=True)
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)


def write_report(path: Path, payload: dict) -> None:
    provenance = payload["provenance"]
    scenario_rows = payload["scenarios"]
    lifecycle = payload["lifecycle"]
    evidence = payload["evidence"]
    shots = payload["screenshots"]

    lines = []
    lines.append("# SpotAsk math rendering benchmark")
    lines.append("")
    lines.append(
        "Generated by `Scripts/benchmark-math.py` from the raw JSONL logs in "
        "`benchmarks/logs/` and the screenshots in `benchmarks/screenshots/`. Every row "
        "comes from an isolated benchmark bundle (`com.spotask.benchmark`) with its own "
        "Application Support directory and defaults domain; the shipping app's session "
        "and preferences were never opened or written."
    )
    lines.append("")
    lines.append(
        "Any accessibility check that fails aborts the run; a report only exists for a "
        "run where every executed check passed."
    )
    lines.append("")

    lines.append("## Provenance")
    lines.append("")
    for target, info in provenance.items():
        lines.append(f"### {target}")
        lines.append("")
        lines.append(f"- source: `{info['source']}`")
        lines.append(f"- HEAD: `{info['head']}`")
        lines.append(f"- build command: `{info['build_command']}`")
        lines.append(f"- product sha256: `{info['product_sha256']}`")
        lines.append(f"- source fingerprint: `{info['source_fingerprint']}`")
        lines.append(
            f"- files hashed for the fingerprint: {info['source_files_hashed']} "
            "(tracked and untracked under Sources/, Vendor/, Package.swift)"
        )
        lines.append(f"- installed binary sha256: `{info['installed_sha256']}`")
        lines.append(f"- worktree diff fingerprint: `{info['worktree_diff_sha256']}`")
        if info.get("baseline_ref"):
            lines.append(f"- baseline ref: `{info['baseline_ref']}`")
            lines.append(f"- benchmark control patch sha256: `{info['baseline_patch_sha256']}`")
        lines.append(f"- swift: `{info['swift_version']}`")
        lines.append(f"- measured at: {info['measured_at']}")
        lines.append("")

    lines.append("## Scenarios (three launches each)")
    lines.append("")
    lines.append(
        "Each row is a fresh process, a fresh session file and a fresh Application Support "
        "directory. Physical footprint comes from `/usr/bin/footprint -f bytes`, sampled at "
        "content-ready and again after a 2 s settle; the peak column is RSS sampled every "
        "200 ms for the lifetime of the process. Ready latency is measured from process "
        "spawn to the accessibility tree containing the expected content."
    )
    lines.append("")

    rows = []
    for scenario_name, entries in scenario_rows.items():
        for target in ("baseline", "integrated"):
            records = [row for row in entries if row["target"] == target]
            if not records:
                continue
            ready = [row.get("footprint_mib_ready") for row in records]
            settled = [row.get("footprint_mib_settled") for row in records]
            peak = [row.get("rss_peak_mib") for row in records]
            ready_ms = [row["timings_ms"]["ready_total"] for row in records]
            formula_ms = [row["timings_ms"]["formula"] for row in records if row["timings_ms"]["formula"]]
            expanded_ms = [
                row["timings_ms"]["expanded_content"]
                for row in records
                if row["timings_ms"].get("expanded_content")
            ]
            stalls = [
                (row.get("stalls") or {}).get("maxDriftMs")
                for row in records
                if (row.get("stalls") or {}).get("maxDriftMs") is not None
            ]
            scope = "strict" if target == "integrated" else "container-only"
            rows.append([
                scenario_name,
                target,
                scope,
                _range(ready),
                _range(settled),
                _range(peak),
                _range(ready_ms),
                _range(formula_ms) if formula_ms else "n/a",
                _range(expanded_ms) if expanded_ms else "n/a",
                _range(stalls) if stalls else "n/a",
            ])
    lines.append(_table(
        ["scenario", "target", "AX scope", "footprint ready (MiB)", "footprint settled (MiB)",
         "RSS peak (MiB)", "ready (ms)", "formula ready (ms)", "expand (ms)",
         "stall max (ms)"],
        rows,
    ))
    lines.append("")
    lines.append(
        "`container-only` means the build exposes no accessibility text for math messages "
        "(see the accessibility evidence below), so its rows are memory references only and "
        "its checks cover window and answer-container presence."
    )
    lines.append("")

    lines.append("## Sample sizes")
    lines.append("")
    sample_rows = []
    for name, scenario in payload["samples"].items():
        sample_rows.append([
            name,
            scenario["words"],
            scenario["formulas"],
            scenario["characters"],
        ])
    lines.append(_table(["scenario", "words", "formulas", "characters"], sample_rows))
    lines.append("")

    if lifecycle:
        lines.append("## Single-PID session lifecycle")
        lines.append("")
        lines.append(
            "One process, one PID. Each cycle replaces the session file, asks the app to "
            "reload it through the benchmark-only command channel, then verifies the new "
            "question, answer and formula are visible and the previous cycle's question is "
            "gone. Any failed check aborts the run. The six-line table is followed by the "
            "full per-cycle trace."
        )
        lines.append("")
        cycle_rows = []
        for target, data in lifecycle.items():
            cycles = data["cycles"]
            if not cycles:
                continue
            values = [row["footprint_mib"] for row in cycles if row["footprint_mib"]]
            cycle_rows.append([
                target,
                len(cycles),
                f"{cycles[0]['footprint_mib']:.2f}",
                f"{cycles[len(cycles) // 2]['footprint_mib']:.2f}",
                f"{cycles[-1]['footprint_mib']:.2f}",
                f"{max(values):.2f}",
                _fmt(data.get("post_reclaim_mib")),
                _fmt(data.get("post_rerender_mib")),
                _fmt(data.get("rss_peak_mib")),
            ])
        lines.append(_table(
            ["target", "cycles", "cycle 1 (MiB)", "mid (MiB)", "cycle N (MiB)",
             "peak observed (MiB)", "after clear+reclaim", "after re-render", "RSS peak"],
            cycle_rows,
        ))
        lines.append("")
        for target, data in lifecycle.items():
            stalls = data.get("stalls") or {}
            lines.append(f"### {target} per-cycle trace")
            lines.append("")
            trace_rows = []
            for row in data["cycles"]:
                timeline = row.get("timeline") or {}
                trace_rows.append([
                    row["cycle"],
                    row.get("messageCount"),
                    row.get("sessionIdentity"),
                    f"{row['footprint_mib']:.2f}",
                    _fmt(timeline.get("contentMs")),
                    _fmt(timeline.get("formulaMs")),
                    "PASS" if all(check["ok"] for check in row.get("checks", [])) else "FAIL",
                ])
            lines.append(_table(
                ["cycle", "messages", "session", "footprint (MiB)", "content (ms)",
                 "formula (ms)", "AX"],
                trace_rows,
            ))
            lines.append("")
            if stalls:
                lines.append(
                    f"- main-thread timer drift max {stalls.get('maxDriftMs', 0):.2f} ms over "
                    f"{stalls.get('samples', 0)} samples; "
                    f"{stalls.get('over50ms', 0)} samples over 50 ms."
                )
                lines.append("")

    if payload.get("costs"):
        lines.append("## Cost of the new renderer, as measured")
        lines.append("")
        lines.append(
            "Every emitter here is the settled footprint (2 s after content-ready) of the same "
            "sample rendered by both builds. Positive numbers are what the new renderer costs on "
            "this machine; they are observations, not budgets."
        )
        lines.append("")
        cost_rows = []
        for row in payload["costs"]:
            cost_rows.append([
                row["scenario"],
                f"{row['baseline_mib']:.2f}",
                f"{row['integrated_mib']:.2f}",
                f"{row['delta_mib']:+.2f}",
                f"{row['delta_percent']:+.1f}%",
            ])
        lines.append(_table(
            ["scenario", "baseline settled (MiB)", "integrated settled (MiB)", "delta", "relative"],
            cost_rows,
        ))
        lines.append("")

    stalls = payload.get("stall_contexts")
    if stalls:
        lines.append("## Main-thread timer drift, by context")
        lines.append("")
        lines.append(
            "The recorder samples a 50 ms timer and reports the largest scheduling drift. Drift is "
            "a symptom, not a located paint stall: it says the main thread was busy, not why. Each "
            "row below was measured in its own context with the statistics reset immediately before."
        )
        lines.append("")
        stall_rows = []
        for name, data in stalls.items():
            if not data:
                continue
            stall_rows.append([
                name,
                f"{data.get('maxDriftMs', 0):.1f}",
                data.get("over50ms", 0),
                data.get("samples", 0),
            ])
        lines.append(_table(["context", "max drift (ms)", "samples > 50 ms", "samples"], stall_rows))
        lines.append("")

    selection = payload.get("selection")
    if selection:
        lines.append("## Selection behaviour (measured, not inferred)")
        lines.append("")
        lines.append(
            "Textual draws attachments into a `Canvas` and gives each `StructuredText` its own "
            "selection model, so a body split around a display block can only select inside one "
            "run. These runs record what a real drag and ⌘C actually produce."
        )
        lines.append("")
        lines.append(
            f"- drag from the paragraph before the block formula to the paragraph after it: "
            f"clipboard `{selection.get('cross_block_clipboard')!r}`; the trailing paragraph was "
            f"{'included' if selection.get('cross_block_includes_after_text') else 'not included'}."
        )
        lines.append(
            f"- drag inside one paragraph: clipboard `{selection.get('single_block_clipboard')!r}`."
        )
        lines.append(
            f"- the same selection after the answer grew underneath it (streaming update): "
            f"`{selection.get('clipboard_after_growth')!r}` — "
            f"{'preserved' if selection.get('selection_survived_growth') else 'lost'} "
            f"(observed, not required: the run is rebuilt when its formulas finish rendering)."
        )
        lines.append("")

    if evidence:
        lines.append("## Interaction evidence")
        lines.append("")
        for key, value in evidence.items():
            lines.append(f"### {key}")
            lines.append("")
            lines.append("```json")
            lines.append(_compact(value))
            lines.append("```")
            lines.append("")

    lines.append("## Screenshots")
    lines.append("")
    shot_rows = []
    for shot in shots:
        shot_rows.append([
            f"`{shot['path']}`",
            f"{shot['width']}×{shot['height']}",
            f"{shot['mean_luminance']:.3f}",
            f"`{shot['sha256'][:16]}…`",
        ])
    lines.append(_table(["file", "size", "mean luminance", "sha256"], shot_rows))
    lines.append("")

    lines.append("## Not measured")
    lines.append("")
    for item in payload["gaps"]:
        lines.append(f"- {item}")
    lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
